-- 三、方案 B（备选，写给"业务决定允许同设备多张活跃工单"的情形）
-- ----------------------------------------------------------------------------
-- 不改表结构，改在事务里把"先查后插"变成"先查并加锁再插"：
--     select ... where inner_code=? and product_type_id=? and task_status in (1,2) FOR UPDATE
-- 依赖：① `insertTaskDto` 已是 `@Transactional`（实测确认）；
--       ② 查询走 `idx_task_inner_status_type`（已在 2026-10-01 由 FIX-4 建立）；
--       ③ InnoDB REPEATABLE READ 下范围条件会取 next-key/gap lock，从而让并发的第二条插入等待。
-- 代价：把一次普通查询升级成**加锁读**，同一设备上的并发建单会串行化，
--       并增加该索引区间上的死锁面（多设备批量建单时尤其要观察）。
-- 取舍：方案 A 是"数据库兜底、无锁竞争"，方案 B 是"不改结构、但把锁带进热路径"。
--       **倾向方案 A**；仅当约束语义被业务否掉时才退回 B。
