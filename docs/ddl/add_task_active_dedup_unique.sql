-- 并发建单收口：同一设备 + 同一工单类型，只允许一张未完成工单（FIX-1）
--
-- 状态：**待评审 + 待数据清理，尚未执行**（AGENTS §2.4：唯一约束变更必须附 DDL 并评审）
-- 执行环境：dkd 库（MySQL 8.0.40）
-- 回滚：见文件末尾
