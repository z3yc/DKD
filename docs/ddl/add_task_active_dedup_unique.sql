--
-- 3.4 ✅ **机制已实测（2026-10-01）**：在**临时探针表**上把整套机制跑了一遍
--     （不动业务表 tb_task），五条都得预期结果：
--
--       ① 同一设备 3 张已完成工单（status=3/4）→ **允许**（键为 NULL，不参与唯一性）
--       ② 插入第 1 张活跃工单 → 成功，键 = `A1:2`
--       ③ 插入同键第 2 张活跃工单 → **被拒**：
--          `ERROR 1062 (23000): Duplicate entry 'A1:2' for key 'fix1_probe.uk_task_active_dedup'`
--       ④ 换设备（`A2:2`）/ 换类型（`A1:1`）→ **允许**（键不同，互不影响）
--       ⑤ 把活跃工单改成已完成 → 键变 NULL → **同键可再建一张活跃单**
--          （这一条最关键：证明约束不会把“上期工单完成、本期再派”的正常业务堵死）
--
--     ⚠️ 一个过程中的真教训（值得写下来）：第一版探针**只建了生成列、漏了唯一索引**，
--        结果“同键第 2 张”直接插进去了——如果只跑正向用例就会得出“机制没问题”的错误结论。
--        **生成列只是把“活跃”表达成可索引的键，拦住重复的是那条 UNIQUE INDEX**，两者缺一不可。
