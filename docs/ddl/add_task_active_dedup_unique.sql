-- ----------------------------------------------------------------------------
-- 一、本文件要解决的问题（以及为什么它不是理论风险）
-- ----------------------------------------------------------------------------
-- `TaskServiceImpl.insertTaskDto` 的防重是「先查后插」：
--     select ... where inner_code=? and product_type_id=? and task_status in (1,2)
--     → 有则拒绝；无则插入
-- 应用层修正（排期 1-8 / FIX-1）已把查询从「只查 2-进行中」改成「1-待接单 + 2-进行中」，
-- 修掉了「刚建的工单是 status=1，而防重查的是 status=2，于是永远查不到自己刚建的工单」这个缺陷。
--
-- 但**并发窗口依旧存在**：两个请求可同时读到「无未完成工单」，然后各插一张。
--
-- ⚠️ **实测证据（2026-10-01，本机 dkd 库）**：库里已经躺着 4 张同设备同类型的活跃工单
--    （tb_task，inner_code='QK8yhIRL'，product_type_id=2，均为 task_status=1）：
--
--      task_id  task_code      task_status  create_time
--      560      202511190010   1            2025-11-19 09:33:18
--      562      202511190012   1            2025-11-19 09:46:17
--      565      202511190015   1            2025-11-19 09:49:10
--      566      202511190016   1            2025-11-19 10:17:31
--
--    时间全部落在 2025-11-19 的 1 小时内，create_type 均为 1。
--    这正好是旧防重缺陷的产物（每张新工单都是 status=1，防重只看 status=2 → 每次都放行），
--    也就是说：**这个缺口已经在真实数据上发生过**，不是"可能发生"。
--
-- 复现检测（可随时跑，正常应返回 0 行）：
--   select inner_code, product_type_id, count(*) c, group_concat(task_id) ids
--     from tb_task where task_status in (1,2)
--    group by inner_code, product_type_id having c > 1;
--
-- ----------------------------------------------------------------------------
-- 二、方案 A（本文件）：DB 级唯一约束——用生成列把"活跃"表达成可索引的键
-- ----------------------------------------------------------------------------
-- 难点：约束的语义是**有条件的**——"只对未完成工单唯一"，已完成的可以有很多张
-- （同一台设备每期补货都是一张新工单）。MySQL **没有 partial index（部分索引）**，
-- 拿不到 `UNIQUE ... WHERE task_status IN (1,2)`。可用的等价手段是：
--
--   生成列：task_status 活跃时产出去重键，非活跃时产出 **NULL**；
--           而 MySQL 唯一索引**允许多个 NULL** → 天然只约束活跃行。
--
-- 为什么 STORED 而不是 VIRTUAL：两者都支持建索引，STORED 少一类版本/引擎差异，
-- 代价是多存一列（varchar(64)，本表量级下可忽略）。选保守的那个。

-- ----------------------------------------------------------------------------
-- 第 0 步（必做）：前置检查——**必须返回 0 行**才能继续
-- ----------------------------------------------------------------------------
SELECT '重复活跃工单（必须为 0 行）' AS 检查项;
SELECT inner_code, product_type_id, count(*) AS 重复数, group_concat(task_id) AS 工单ID
  FROM tb_task
 WHERE task_status IN (1, 2)
 GROUP BY inner_code, product_type_id
HAVING 重复数 > 1;

SELECT 'NULL 键（不参与唯一索引，需确认为 0）' AS 检查项;
SELECT sum(inner_code IS NULL) AS 空设备码, sum(product_type_id IS NULL) AS 空类型
  FROM tb_task WHERE task_status IN (1, 2);

-- 若第一条返回了行 → **先做第 5 步的数据清理（需业务确认）或改用方案 B**，
-- 否则第 1~2 步的 ALTER 会以「Duplicate entry」失败（这不是坏事：它正好证明约束有效）。

-- ----------------------------------------------------------------------------
-- 第 1 步：加生成列
-- ----------------------------------------------------------------------------
ALTER TABLE tb_task
  ADD COLUMN active_dedup_key VARCHAR(64)
    GENERATED ALWAYS AS (
      CASE
        WHEN task_status IN (1, 2)
          THEN CONCAT(inner_code, ':', IFNULL(product_type_id, 0))
        ELSE NULL          -- 非活跃 → NULL → 不参与唯一性（允许历史多张已完成工单）
      END
    ) STORED
    COMMENT '仅对未完成工单（1-待接单/2-进行中）非空：用于唯一约束实现"同设备同类型至多一张活跃工单"（FIX-1）';

-- ----------------------------------------------------------------------------
-- 第 2 步：加唯一索引（真正把并发窗口焊死的地方）
-- ----------------------------------------------------------------------------
-- 为什么放 DB 而不是只改应用代码：应用层的"先查后插"在并发下必然有窗口，
-- 而**业务事实的唯一所有者是 Java + DB**（AGENTS §1 约束 1）。
-- 约束放这里，无论是管理后台、dkd-app 还是 Agent 回调，走的都是同一把锁。
--
-- ⚠️ 这条约束同时是一条**业务规则声明**：
--    「同一设备 + 同一工单类型，最多存在 1 张未完成工单」
--    该规则与现有异常文案「设备有未完成工单，请勿重复创建工单」一致，
--    但**需业务/产品确认它对所有工单类型都成立**（当前库内活跃工单只有类型 1 与 2）。
--    若某类型允许并行多张（例如"同设备的多个独立故障各建一张维修单"），
--    则本索引会把合法流程拒掉——那是**必须在上线前拍板**的事，不能靠"先上了再看"。
ALTER TABLE tb_task
  ADD UNIQUE INDEX uk_task_active_dedup (active_dedup_key);

